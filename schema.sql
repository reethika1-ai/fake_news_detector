-- ==============================================================================
-- Supabase Schema for Fake News & Misinformation Detector
-- Table: prediction_logs
-- ==============================================================================

-- 1. Create table if it doesn't already exist
CREATE TABLE IF NOT EXISTS public.prediction_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    news_text TEXT NOT NULL,
    prediction VARCHAR(50) NOT NULL,
    confidence NUMERIC(5, 2) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Performance index on created_at for fast descending queries
CREATE INDEX IF NOT EXISTS idx_prediction_logs_created_at 
ON public.prediction_logs (created_at DESC);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.prediction_logs ENABLE ROW LEVEL SECURITY;

-- 4. Create policies to allow insertion and querying
-- Note: You can customize these according to your application's security model.
CREATE POLICY "Allow anonymous and service inserts"
ON public.prediction_logs
FOR INSERT
TO anon, authenticated, service_role
WITH CHECK (true);

CREATE POLICY "Allow anonymous and service reads"
ON public.prediction_logs
FOR SELECT
TO anon, authenticated, service_role
USING (true);

-- End of schema

